#!/usr/bin/env node
/**
 * gen-og-cards.mjs — draw the generated social share cards into public/og/.
 *
 *   npm run og            # rebuild every card
 *   npm run og -- --if-missing   # what `npm run dev` calls: build once, then get out of the way
 *
 * WHAT A CARD IS. 1200 × 630 of the site's own black with one mark drawn large
 * in the middle. Nothing else — no title, no wordmark. Two reasons, and the
 * second is the load-bearing one:
 *
 *   • Every platform that renders an unfurl already prints the title, the
 *     description and the domain as live text beside the picture. Repeating any
 *     of it inside the image is redundant at best and, at the size WhatsApp
 *     draws a preview, illegible.
 *   • Text in the image means a font, and Sharp renders text through whatever
 *     fontconfig hands it. This site's face is a self-hosted woff2 that no CI
 *     runner has installed, so a card with type on it would silently come out
 *     in DejaVu Sans on the machine that actually builds the deploy. A picture
 *     that cannot be got wrong is worth more here than a picture with a byline.
 *
 * TWO FAMILIES, ONE TREATMENT.
 *
 *   public/og/visualizations/<thumb>.png   from public/visualizations/thumbs/,
 *       the 128 × 80 Plot marks generated by the loaders in viz/src/thumbs. They
 *       are drawn in `currentColor` and so arrive with no colour at all.
 *   public/og/articles/<slug>.png          from each post's `thumb`, the line
 *       icons carried over from the Jekyll blog index. They are BLACK art on
 *       transparency — the site renders them with `filter: invert(1)`
 *       (.article__mark in src/pages/articles.astro) — so the card inverts them
 *       the same way rather than compositing black on black.
 *
 * Keyed by POST SLUG, not by thumb filename: a post's frontmatter names its
 * thumb with a relative path, Astro turns that into an `ImageMetadata` carrying
 * only a hashed build URL, and there is no way back from that to the source
 * file. The slug is the one identifier this script and [slug].astro can both
 * compute. So this script reads the frontmatter itself — the same file Astro
 * reads — rather than being told the mapping twice.
 *
 * GENERATED OUTPUT, LIVING IN public/. The same bargain as
 * scripts/build-visualizations.mjs: public/ is what `astro dev` serves and what
 * `astro build` copies, so writing here means dev and production resolve the
 * same URLs with no ordering rule to remember. public/og/ is gitignored, and
 * this script clears it first so a renamed post cannot leave a stale card
 * behind for a URL that no longer exists.
 */

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { basename, dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

import { CARD, CARD_INK, CARD_MARK, PORTRAIT_PATH, PORTRAIT_SIZE } from "../src/lib/og-card.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "og");
const postsDir = join(root, "src", "content", "posts");
const vizThumbs = join(root, "public", "visualizations", "thumbs");

// `npm run dev` passes this so a fresh checkout gets its cards once and every
// later restart skips a second of Sharp. `npm run og` and `npm run build` force
// a rebuild, which is what picks up a new post or a retuned mark.
if (process.argv.includes("--if-missing") && existsSync(outDir)) {
  console.log("og cards: public/og already built — skipping (npm run og to rebuild)");
  process.exit(0);
}

// ── The canvas ───────────────────────────────────────────────────────────────
// One flat rectangle of --bg, reused for every card. Built from a raw buffer
// rather than an SVG so there is no renderer between the constant and the
// pixels: the audit compares the shipped PNG's dimensions against the numbers
// og-card.mjs also feeds into the <meta> tags, and this is the end of the chain
// that has to be exactly right.
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const canvas = () =>
  sharp({
    create: {
      width: CARD.width,
      height: CARD.height,
      channels: 4,
      background: {
        r: rgb(CARD_INK.bg)[0],
        g: rgb(CARD_INK.bg)[1],
        b: rgb(CARD_INK.bg)[2],
        alpha: 1,
      },
    },
  });

/**
 * Composite one already-sized mark into the middle of a card and write it.
 *
 * `gravity: "centre"` rather than computed offsets: Sharp does the arithmetic
 * against the real decoded size of the mark, so a mark whose aspect ratio does
 * not divide evenly into its box still lands centred instead of half a pixel
 * out.
 *
 * PNG, not JPEG. These are large flat fields of one colour with hard-edged line
 * art over them — the case JPEG is worst at, where its ringing shows up as a
 * grey halo around every stroke. `palette: true` quantises to an indexed PNG,
 * which for two colours and their antialiasing is both smaller and lossless
 * enough that nothing is visible; a card lands around 20 KB against the 5 MB
 * every platform allows.
 */
async function writeCard(path, mark) {
  await mkdir(dirname(path), { recursive: true });
  const buf = await canvas()
    .composite([{ input: mark, gravity: "centre" }])
    .png({ palette: true, compressionLevel: 9 })
    .toBuffer();
  await writeFile(path, buf);
  return buf.length;
}

// The box every mark is fitted inside, in pixels. See CARD_MARK in og-card.mjs.
const box = {
  width: Math.round(CARD.width * CARD_MARK.width),
  height: Math.round(CARD.height * CARD_MARK.height),
};

/**
 * Fit a mark into the box without cropping it, and never stretch it.
 *
 * `fit: "inside"` on both axes, so whichever axis binds decides — an 8:5 chart
 * comes out full width, a square icon comes out full height, and a tall narrow
 * glyph comes out full height and narrow. Enlargement is allowed, deliberately:
 * after trimming, the smallest article thumbs are around 180px tall and would
 * otherwise sit at a third of the card's height beside thumbs drawn at full
 * size. These are flat, high-contrast glyphs — the case a Lanczos upscale
 * handles well — and a consistent set of cards is worth more than the sharpness
 * lost at 2×.
 */
const fitInBox = (pipe) => pipe.resize({ ...box, fit: "inside", kernel: "lanczos3" });

// ── Visualization marks ──────────────────────────────────────────────────────
/**
 * Rasterise one `currentColor` SVG mark at card scale.
 *
 * TWO EDITS TO THE SVG, both necessary and both narrow:
 *
 *   1. `currentColor` → the ink. There is no cascade out here, and CSS says an
 *      unresolved `color` is black — so left alone every one of these marks
 *      would render black on black and the card would ship empty. The
 *      substitution is global because mark.js hoists the colour onto the root
 *      but leaves it on the few elements that deliberately state their own.
 *   2. The root's width/height, and only the root's. librsvg rasterises an SVG
 *      at its intrinsic size, so a 128 × 80 mark would come out 128 × 80 and be
 *      upscaled by the compositor into mush. Rewriting the attributes (the
 *      viewBox is untouched, so the geometry just scales) renders the vector at
 *      full size instead. `<image>` elements inside these marks carry their own
 *      width/height, which is why this only ever touches the first tag.
 *
 * Rendered at TWICE the box and then fitted down. Two of these marks — the
 * glucose heatmap and the New York parcel map — are a PNG held as a mask rather
 * than vector geometry (kilobytes instead of hundreds of them; see maskedRaster
 * in viz/src/thumbs/mark.js), so they are the one thing here that does not
 * scale for free. Rendering long and resampling down is what keeps their edges
 * from going to mush, and costs the vector marks nothing.
 *
 * Trimmed like the article thumbs, and for the same reason: several of these
 * frames are mostly empty. The New York mark carries the whole projection's
 * bounding box around a city sitting in its right half, so untrimmed it draws
 * a small map well off the card's centre.
 */
async function vizMark(file) {
  const raw = readFileSync(file, "utf8");
  const width = box.width * 2;

  const sized = raw.replace(/^<svg\b[^>]*>/, (tag) => {
    const viewBox = tag.match(/viewBox="([^"]+)"/);
    if (!viewBox) throw new Error(`${basename(file)} has no viewBox to scale against`);
    const [, , vw, vh] = viewBox[1]
      .trim()
      .split(/[\s,]+/)
      .map(Number);
    const height = Math.round((width * vh) / vw);
    return tag
      .replace(/\swidth="[^"]*"/, "")
      .replace(/\sheight="[^"]*"/, "")
      .replace(/^<svg/, `<svg width="${width}" height="${height}"`);
  });

  const inked = sharp(Buffer.from(sized.replaceAll("currentColor", CARD_INK.fg)));
  return fitInBox(inked.trim({ threshold: 1 }))
    .png()
    .toBuffer();
}

// ── Article thumbs ───────────────────────────────────────────────────────────
/**
 * Bring one post thumb up to card scale, in the colour the site shows it in.
 *
 * TRIM FIRST. These arrive as 288–700px squares carrying a lot of transparent
 * margin — grethumb.png is 400 × 400 around a drawing that is 245 × 200 — and
 * that margin is not a design decision anyone made, it is what the icons
 * happened to be exported at. Sizing an untrimmed thumb into the box draws the
 * ink at half the intended size and leaves the card looking empty (it did, on
 * the first pass). Trimming makes every thumb fill the same optical area no
 * matter what it was exported with.
 *
 * THEN INVERT AND TINT IN ONE STEP. `linear(a, b)` applies `a × input + b` per
 * channel, so a NEGATIVE slope inverts and rescales at once: black ink lands on
 * the ink colour, white lands on the card's black. That is `filter: invert(1)`
 * — what .article__mark in src/pages/articles.astro does to show these on a
 * dark page — with the ink brought down to --text in the same pass.
 *
 * It has to be one operation rather than `negate()` then `linear()`, and this
 * is the subtle part: Sharp applies its pipeline in a FIXED internal order, not
 * in call order, and levels come before inversion. Chaining the two reads
 * correctly and silently produces ink at 29/255 — very dark grey ink on black,
 * i.e. an almost blank card. Verified, not assumed.
 *
 * Alpha is untouched by `linear`, so antialiased edges keep their coverage and
 * composite cleanly onto the card instead of acquiring a fringe. Mid-tones
 * survive too, which matters: three of these thumbs carry opaque WHITE detail
 * inside the drawing, and an alpha-mask-and-fill approach would flood it.
 *
 * thesis-icon.svg is the one SVG in the set and takes the other branch. It
 * states no fill at all, so its paths inherit CSS's initial black — setting the
 * fill on the root, which none of its own elements override, is the same
 * substitution `currentColor` gets above, and rasterises at full size for free.
 */
async function articleMark(file) {
  if (extname(file) === ".svg") {
    const raw = readFileSync(file, "utf8");
    const inked = raw.replace(
      /^<svg\b[^>]*>/,
      (tag) => `${tag.replace(/\sfill="[^"]*"/, "").slice(0, -1)} fill="${CARD_INK.fg}">`,
    );
    return fitInBox(sharp(Buffer.from(inked), { density: 300 }).trim({ threshold: 1 }))
      .png()
      .toBuffer();
  }

  // The ink as a 0–255 level. The three channels of --text are equal, so one
  // read is the whole colour; a non-grey ink would need three slopes here.
  const fg = parseInt(CARD_INK.fg.slice(1, 3), 16);
  return fitInBox(
    sharp(file)
      .trim({ threshold: 1 })
      .linear(-fg / 255, fg),
  )
    .png()
    .toBuffer();
}

/**
 * The `thumb:` line out of a post's frontmatter, resolved to a real path.
 *
 * A three-line parse rather than a YAML dependency: this reads ONE scalar out
 * of the block Astro has already validated against the content schema, so a
 * malformed file fails the build a moment later with a far better message than
 * anything this could produce. Anything it cannot find is reported and skipped
 * — a post with no thumb is legal (the schema marks it optional) and simply
 * falls back to the portrait.
 */
function thumbFor(postFile) {
  const source = readFileSync(postFile, "utf8");
  const front = source.split(/^---\s*$/m)[1] ?? "";
  // A post that names its own picture never reaches its thumb — [slug].astro
  // stops at `ogImage`. Generating the card anyway would leave a file nothing
  // links to, which is also what the audit's orphan check would then trip on.
  if (/^ogImage:/m.test(front)) return { skip: "has its own ogImage" };
  const line = front.match(/^thumb:\s*(.+)$/m);
  if (!line) return { skip: "no thumb in frontmatter" };
  const rel = line[1].trim().replace(/^["']|["']$/g, "");
  const path = resolve(dirname(postFile), rel);
  return existsSync(path) ? path : { missing: path };
}

// ── Build ────────────────────────────────────────────────────────────────────
await rm(outDir, { recursive: true, force: true });

const built = [];
// Two different absences, told apart deliberately. A post that names its own
// `ogImage` needs no card and never wanted one — that is the design working, and
// printing it as a warning would train everyone to ignore this script's output.
// A thumb pointing at a file that is not there is a broken post.
const covered = [];
const problems = [];

// The visualization marks exist only after `npm run viz` has run. Absent is a
// legitimate state of a fresh checkout, not an error: Viz.astro checks for the
// card and falls back to the portrait, so the pages still share correctly.
if (existsSync(vizThumbs)) {
  for (const name of readdirSync(vizThumbs).filter((f) => f.endsWith(".svg"))) {
    const slug = basename(name, ".svg");
    const bytes = await writeCard(
      join(outDir, "visualizations", `${slug}.png`),
      await vizMark(join(vizThumbs, name)),
    );
    built.push([`visualizations/${slug}`, bytes]);
  }
} else {
  problems.push(`no visualization marks at ${vizThumbs} — run \`npm run viz\``);
}

for (const name of readdirSync(postsDir).filter((f) => f.endsWith(".md"))) {
  const slug = basename(name, ".md");
  const thumb = thumbFor(join(postsDir, name));
  if (typeof thumb === "object") {
    (thumb.skip ? covered : problems).push(
      `${slug}: ${thumb.skip ?? `thumb not found at ${thumb.missing}`}`,
    );
    continue;
  }
  const bytes = await writeCard(join(outDir, "articles", `${slug}.png`), await articleMark(thumb));
  built.push([`articles/${slug}`, bytes]);
}

// ── The sitewide portrait ────────────────────────────────────────────────────
// Every route without a picture or a mark of its own shares this: /about,
// /articles, /papers, /talks, /projects, /images, the home page.
//
// Drawn HERE rather than by Astro's image service, so it lands at one fixed URL
// that survives a re-export of the portrait and an upgrade of Astro — see
// PORTRAIT_PATH in src/lib/og-card.mjs for why a hashed og:image quietly rots
// every preview already pasted somewhere.
//
// `position: "attention"` is Sharp's saliency crop, which keeps the face in
// frame when squaring a 1571 × 1600 source. `withoutEnlargement` is deliberately
// NOT set: the tags in src/lib/og.ts declare PORTRAIT_SIZE, and a crawler that
// lays the card out against a declared size the file does not have draws the
// preview wrong. The source is large enough that nothing is invented.
const portraitSrc = join(root, "src", "assets", "portrait-open.webp");
if (!existsSync(portraitSrc)) {
  problems.push(`portrait not found at ${portraitSrc} — every share falls back to nothing`);
} else {
  const dest = join(root, "public", PORTRAIT_PATH.replace(/^\//, ""));
  await mkdir(dirname(dest), { recursive: true });
  const buf = await sharp(portraitSrc)
    .resize(PORTRAIT_SIZE, PORTRAIT_SIZE, { fit: "cover", position: "attention" })
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  await writeFile(dest, buf);
  built.push([PORTRAIT_PATH.replace(/^\//, "").replace(/\.jpg$/, ""), buf.length]);
}

const total = built.reduce((n, [, b]) => n + b, 0);
const largest = built.length ? Math.max(...built.map(([, b]) => b)) : 0;
console.log(
  `og cards: ${built.length} card(s) at ${CARD.width}×${CARD.height} → public/og ` +
    `(${(total / 1024).toFixed(0)} KB total, largest ${(largest / 1024).toFixed(0)} KB)` +
    (covered.length ? `; ${covered.length} post(s) share their own picture instead` : ""),
);
for (const note of problems) console.warn(`og cards: WARNING — ${note}`);
